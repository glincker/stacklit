func TestIdempotentAndUninstall(t *testing.T) {
	dir := t.TempDir()
	// A pre-existing user file must survive install and uninstall.
	if err := os.WriteFile(filepath.Join(dir, "CLAUDE.md"), []byte("# mine\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	o := Options{Tools: Registry(), Claude: ClaudeOptions{PreToolHook: true, SessionHook: true, Skill: true}}
	run(t, dir, o, false)
	_, r2 := run(t, dir, o, false)
	if r2.Changed != 0 {
		t.Fatalf("second run changed %d files", r2.Changed)
	}
	b, _ := os.ReadFile(filepath.Join(dir, "CLAUDE.md"))
	if strings.Count(string(b), "stacklit:start") != 1 {
		t.Fatalf("duplicated block:\n%s", b)
	}
	for _, p := range []string{"AGENTS.md", "GEMINI.md", ".github/copilot-instructions.md", ".cursor/rules/stacklit.mdc",
		".mcp.json", ".gemini/settings.json", ".vscode/mcp.json", "opencode.json", ".codex/config.toml",
		".claude/settings.json", ".claude/skills/stacklit/SKILL.md", ".continue/mcpServers/stacklit.yaml"} {
		if _, err := os.Stat(filepath.Join(dir, p)); err != nil {
			t.Errorf("missing %s", p)
		}
	}

	o.Uninstall = true
	run(t, dir, o, false)
	b, _ = os.ReadFile(filepath.Join(dir, "CLAUDE.md"))
	if strings.TrimSpace(string(b)) != "# mine" {
		t.Fatalf("user content damaged: %q", b)
	}
	var left []string
	_ = filepath.Walk(dir, func(p string, i os.FileInfo, _ error) error {
		if !i.IsDir() && !strings.HasSuffix(p, "CLAUDE.md") {
			left = append(left, p)
		}
		return nil
	})
	if len(left) != 0 {
		t.Fatalf("uninstall left files: %v", left)
	}
}

func TestDryRunWritesNothing(t *testing.T) {
	dir := t.TempDir()
	out, r := run(t, dir, Options{Tools: Registry(), Claude: ClaudeOptions{PreToolHook: true}}, true)
	if r.Changed == 0 || !strings.Contains(out, "would create") {
		t.Fatalf("dry run reported nothing: %s", out)
	}
	ents, _ := os.ReadDir(dir)
	if len(ents) != 0 {
		t.Fatalf("dry run wrote files: %v", ents)
	}
}

func TestMCPMergePreservesOtherServers(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, ".mcp.json")
	if err := os.WriteFile(p, []byte(`{"mcpServers":{"other":{"command":"x"}}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	tool, _ := Lookup("claude")
	run(t, dir, Options{Tools: []Tool{tool}}, false)
	b, _ := os.ReadFile(p)
	if !strings.Contains(string(b), "other") || !strings.Contains(string(b), "stacklit") {
		t.Fatalf("bad merge: %s", b)
	}
	run(t, dir, Options{Tools: []Tool{tool}, Uninstall: true}, false)
	b, _ = os.ReadFile(p)
	if !strings.Contains(string(b), "other") || strings.Contains(string(b), `"stacklit"`) {
		t.Fatalf("bad uninstall: %s", b)
	}
}

