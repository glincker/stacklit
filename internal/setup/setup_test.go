func run(t *testing.T, root string, o Options, dry bool) (string, *Runner) {
	t.Helper()
	var out bytes.Buffer
	r := &Runner{Root: root, DryRun: dry, Out: &out}
	o.Root = root
	if o.Index == nil {
		o.Index = testIdx()
	}
	o.NoGitHook = true
	if err := Run(r, o); err != nil {
		t.Fatal(err)
	}
	return out.String(), r
}

