package parser

import (
	"strings"
	"testing"
	"time"
)

func TestFallbackReasons(t *testing.T) {
	lim := Limits{MaxBytes: 100, MaxLineLen: 50, Generated: true}
	cases := []struct {
		name, rel, body, want string
	}{
		{"small", "a.ts", "export const a = 1\n", ""},
		{"large", "a.ts", strings.Repeat("x\n", 80), FallbackLarge},
		{"minified", "a.ts", "var a=" + strings.Repeat("1+", 30) + "1", FallbackMinified},
		{"header", "a.ts", "// Code generated by tool. DO NOT EDIT.\nexport const a = 1\n", FallbackGenerated},
		{"name", "a.pb.ts", "export const a = 1\n", FallbackGenerated},
		{"min", "a.min.js", "var a=1", FallbackGenerated},
	}
	for _, c := range cases {
		if got := lim.fallbackReason(c.rel, []byte(c.body)); got != c.want {
			t.Errorf("%s: got %q, want %q", c.name, got, c.want)
		}
	}
	if (Limits{}).fallbackReason("a.ts", []byte(strings.Repeat("x", 1<<20))) != "" {
		t.Error("zero limits must disable every check")
	}
}

// A parse that exceeds its budget must return promptly with a lightweight
// result instead of blocking the worker.
func TestParseTimeoutFallsBack(t *testing.T) {
	var b strings.Builder
	for i := 0; i < 4000; i++ {
		b.WriteString("export function f")
		b.WriteString(strings.Repeat("a", i%7))
		b.WriteString("(x: number) { return [x, {y: x}]; }\n")
	}
	info, err := ParseContentWith("big.ts", []byte(b.String()), Limits{ParseTimeout: time.Microsecond})
	if err != nil {
		t.Fatal(err)
	}
	if info.Fallback != FallbackTimeout || info.Language == "" || info.LineCount != 4000 {
		t.Fatalf("expected timeout fallback with line count, got %+v", info)
	}
}
